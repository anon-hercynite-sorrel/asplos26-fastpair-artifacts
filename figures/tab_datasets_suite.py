"""Emit the fifteen-column tab:datasets rows from a suite campaign's B300 measurements.

    uv run figures/tab_datasets_suite.py
    uv run figures/tab_datasets_suite.py --suite-id paper-20260821

Definitions come from suite.py: token-weighted mean decoded bytes per code, and
at-rest compression ratio including the dictionary and offset sidecar. Missing
cells print --. Rows are not averaged across devices.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import suite as S  # noqa: E402


def fmt_int(v):
    if v is None:
        return "--"
    return f"{v:,}".replace(",", "\\,")


def fmt(v, spec, suffix=""):
    return "--" if v is None else format(v, spec) + suffix


BASELINE_NAMES = ("DE", "Zstd", "gANS")


def ratio_pair(points):
    """Ratios at the fastest and highest-compression measured settings.

    Break rate ties toward higher compression and ratio ties toward faster decode.
    """
    if not points:
        return None
    fastest = max(points, key=lambda p: (p[1], p[0]))
    compact = max(points, key=lambda p: (p[0], p[1]))
    return fastest[0], compact[0]


def baseline_ratios(root, chip, ds, col, software):
    """Paired baseline ratios from the same sweeps used by the evaluation figures."""
    if chip != "b300":
        raise ValueError("the paper's Zstd frame sweep is available only for b300")
    points = {
        "DE": S.de_points(root, chip, ds, col),
        "Zstd": S.zstd_best_points(ds, col),
    }
    record = software.get((ds, col)) or {}
    passes = [record.get("codecs") or {}]
    passes += [p.get("codecs") or {} for p in record.get("chunk_sweep", [])]
    for name in BASELINE_NAMES[2:]:
        points[name] = []
        for codecs in passes:
            entry = codecs.get(name) or {}
            if not (entry.get("supported") and entry.get("valid")
                    and not entry.get("validation_failed") and entry.get("ratio")):
                continue
            rate = S._rate(entry, S._payload(record))
            if rate:
                points[name].append((entry["ratio"], rate))
    return {name: ratio_pair(values) for name, values in points.items()}


def row(label, ds, col, c12, c16, cf, baselines):
    """One table row: dictionary statistics followed by baseline compression ratios.

    FSST-12 has no <=8B column: gpu.frac_le8 is 1.0 on every FSST row by construction, so the
    cell would carry no information."""
    cells = [
        fmt_int(S.tokens(c16)), fmt(S.mean_len(c16), ".1f"),
        fmt(S.frac_le8(c16) * 100 if S.frac_le8(c16) is not None else None, ".0f", "\\%"),
        fmt(S.ratio(c16), ".1f"),
        fmt_int(S.tokens(c12)), fmt(S.mean_len(c12), ".1f"),
        fmt(S.frac_le8(c12) * 100 if S.frac_le8(c12) is not None else None, ".0f", "\\%"),
        # NO GRANULARITY PASSED, deliberately: this table pairs the ratio with no decode rate,
        # so there is no kernel whose K it should follow. It reports the shipped K=6 charge.
        # fig_perf_real, which does pair the two, charges its plotted kernel's own K.
        fmt(S.ratio(c12), ".1f"),
        fmt_int(S.tokens(cf)), fmt(S.mean_len(cf), ".1f"), fmt(S.ratio(cf), ".1f"),
    ]
    for name in BASELINE_NAMES:
        pair = baselines[name] or (None, None)
        cells.extend(fmt(value, ".1f") for value in pair)
    return f"{label} & " + " & ".join(cells) + " \\\\"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite-id", default=None)
    ap.add_argument("--chip", default="b300")
    a = ap.parse_args()

    root = S.latest_root(a.suite_id)
    if root is None:
        sys.exit("no results/suite-* directory found")
    c12 = S.cells(root, a.chip, "boost", "onpair")
    c16 = c12
    cf = S.cells(root, a.chip, "boost", "fsst12")

    def pick(store, ds, col, bits):
        return store.get((ds, col, bits))

    software = S.sw_rows(S.sw_root_for(a.chip), a.chip)
    missing = []
    out = []
    for group, rows in (("real", S.REAL), ("gen", S.GEN)):
        for label, ds, col in rows:
            r12, r16 = pick(c12, ds, col, 12), pick(c16, ds, col, 16)
            rf = pick(cf, ds, col, 12)
            for name, cell in (("OnPair-12", r12), ("OnPair-16", r16), ("FSST-12", rf)):
                if cell is None:
                    missing.append(f"{ds}/{col} {name}")
            baselines = baseline_ratios(root, a.chip, ds, col, software)
            for name, value in baselines.items():
                if value is None:
                    missing.append(f"{ds}/{col} {name} C.R.")
            out.append(row(label, ds, col, r12, r16, rf, baselines))
        if group == "real":
            out.append("\\midrule")

    print(f"% GENERATED by figures/tab_datasets_suite.py from results/{root.name}/{a.chip}")
    print("% Ratio = sample_bytes/on_disk_bytes (at rest); Len = sample_bytes/gpu.total_tokens")
    print("% Baseline C.R. = ratios at fastest decode / highest compression across tested settings")
    print("\n".join(out))
    if missing:
        print(f"\n% INCOMPLETE: {len(missing)} cells absent -> printed as --", file=sys.stderr)
        for m in missing[:10]:
            print(f"%   {m}", file=sys.stderr)
    else:
        print(f"\n% all 15 columns x 3 dictionary codecs and 3 baseline ratio pairs present", file=sys.stderr)


if __name__ == "__main__":
    main()
